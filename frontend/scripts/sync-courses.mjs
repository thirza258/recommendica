// Regenerates everything derived from the curriculum in src/data/courses.ts:
//
//   - src/data/courseCatalog.ts: the lightweight summary the landing page
//     imports, so the main bundle does not carry every lesson's text;
//   - the per-course <url> sections of public/sitemap.xml and
//     public/sitemap-courses.xml, and their dates in public/sitemap-index.xml;
//   - the same sections inside the backend's sitemap strings
//     (../backend/recommendica/urls.py), when the backend is checked out.
//
// Run `npm run courses:sync` after adding, removing, or retiming a course or
// lesson. `npm run courses:sync -- --check` only reports stale files, and the
// curriculum tests fail while any file is stale.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COURSES } from "../src/data/courses.ts";

const SITE = "https://recommendica.nevatal.id";
/** Bump when course content changes so crawlers revisit the course pages. */
export const COURSES_LASTMOD = "2026-11-09T00:00:00+00:00";

const frontend = new URL("../", import.meta.url);
const fromFrontend = (relative) => fileURLToPath(new URL(relative, frontend));

export const CATALOG_FILE = fromFrontend("src/data/courseCatalog.ts");
const SITEMAP_FILES = [
  fromFrontend("public/sitemap.xml"),
  fromFrontend("public/sitemap-courses.xml"),
];
const SITEMAP_INDEX = fromFrontend("public/sitemap-index.xml");
const BACKEND_URLS = fromFrontend("../backend/recommendica/urls.py");
const BACKEND_SITEMAPS = ["SITEMAP_XML_CONTENT", "SITEMAP_COURSES_XML_CONTENT"];

export function courseSummaries(courses = COURSES) {
  return courses.map((course) => ({
    id: course.id,
    title: course.title,
    category: course.category,
    description: course.description,
    lessons: course.lessons.length,
    minutes: course.lessons.reduce((sum, lesson) => sum + lesson.minutes, 0),
  }));
}

export function catalogModule(courses = COURSES) {
  const entries = courseSummaries(courses).map((summary) => {
    const fields = Object.entries(summary).map(
      ([key, value]) => `    ${key}: ${JSON.stringify(value)},`,
    );
    return ["  {", ...fields, "  },"].join("\n");
  });
  return [
    "// Generated by scripts/sync-courses.mjs from src/data/courses.ts.",
    "// Do not edit by hand: run `npm run courses:sync` after changing the curriculum.",
    "//",
    "// A lightweight summary so the landing page can describe every course without",
    "// bundling the lessons themselves.",
    "",
    "export interface CourseSummary {",
    "  id: string;",
    "  title: string;",
    "  category: string;",
    "  description: string;",
    "  lessons: number;",
    "  minutes: number;",
    "}",
    "",
    "export const COURSE_CATALOG: CourseSummary[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

function urlEntry(loc, priority) {
  return [
    "  <url>",
    `    <loc>${loc}</loc>`,
    `    <xhtml:link rel="alternate" hreflang="x-default" href="${loc}" />`,
    `    <xhtml:link rel="alternate" hreflang="en" href="${loc}" />`,
    `    <lastmod>${COURSES_LASTMOD}</lastmod>`,
    "    <changefreq>monthly</changefreq>",
    `    <priority>${priority}</priority>`,
    "  </url>",
  ].join("\n");
}

function sectionRule(label) {
  // XML comments may not contain "--".
  const text = `  <!-- ── ${label.replaceAll("--", "–")} `;
  return `${text}${"─".repeat(Math.max(3, 76 - text.length))} -->`;
}

export function courseSections(courses = COURSES) {
  return courses
    .map((course, index) =>
      [
        sectionRule(`Course ${index + 1}: ${course.title}`),
        urlEntry(`${SITE}/courses/${course.id}`, "0.8"),
        ...course.lessons.map((lesson) =>
          urlEntry(`${SITE}/courses/${course.id}/${lesson.id}`, "0.7"),
        ),
      ].join("\n"),
    )
    .join("\n\n");
}

/**
 * Replaces the run of per-course sections in one sitemap document and dates
 * the catalog entry. The run starts at the "Course 1" rule and ends at the
 * next section that is not a course, or at </urlset>.
 */
export function syncSitemap(xml, courses = COURSES) {
  const start = xml.indexOf("  <!-- ── Course 1:");
  if (start < 0) throw new Error("Sitemap has no course sections to replace.");
  const end = /\n(?=  <!-- ── (?!Course \d+:))|\n(?=<\/urlset>)/.exec(
    xml.slice(start),
  );
  if (!end) throw new Error("Sitemap course sections have no end.");
  const following = xml.slice(start + end.index + 1);
  const gap = following.startsWith("</urlset>") ? "\n" : "\n\n";
  const synced = xml.slice(0, start) + courseSections(courses) + gap + following;
  return bumpLastmod(synced, `${SITE}/courses`);
}

const escapeRegExp = (text) => text.replace(/[.*+?^$()|[\]{}\\]/g, "\\$&");

/** Moves an entry's <lastmod> forward to COURSES_LASTMOD, never backward. */
function bumpLastmod(xml, loc) {
  const pattern = new RegExp(
    "(<loc>" + escapeRegExp(loc) + "</loc>[\\s\\S]*?<lastmod>)([^<]*)(</lastmod>)",
  );
  return xml.replace(pattern, (_, open, date, close) =>
    open + (date < COURSES_LASTMOD ? COURSES_LASTMOD : date) + close,
  );
}

/** The sitemap index dates the two sitemaps that list courses. */
export function syncSitemapIndex(xml) {
  return bumpLastmod(
    bumpLastmod(xml, `${SITE}/sitemap.xml`),
    `${SITE}/sitemap-courses.xml`,
  );
}

export function syncBackendUrls(python, courses = COURSES) {
  let synced = python;
  for (const name of BACKEND_SITEMAPS) {
    const pattern = new RegExp(`(\\n${name} = """)([\\s\\S]*?)(""")`);
    if (!pattern.test(synced)) throw new Error(`${name} not found in urls.py.`);
    synced = synced.replace(
      pattern,
      (_, open, body, close) => open + syncSitemap(body, courses) + close,
    );
  }
  return synced.replace(
    /(\nSITEMAP_INDEX_XML_CONTENT = """)([\s\S]*?)(""")/,
    (_, open, body, close) => open + syncSitemapIndex(body) + close,
  );
}

/** Every derived file paired with its up-to-date contents. */
export function derivedFiles(courses = COURSES) {
  const files = [[CATALOG_FILE, catalogModule(courses)]];
  for (const file of SITEMAP_FILES) {
    files.push([file, syncSitemap(readFileSync(file, "utf8"), courses)]);
  }
  files.push([SITEMAP_INDEX, syncSitemapIndex(readFileSync(SITEMAP_INDEX, "utf8"))]);
  if (existsSync(BACKEND_URLS)) {
    files.push([
      BACKEND_URLS,
      syncBackendUrls(readFileSync(BACKEND_URLS, "utf8"), courses),
    ]);
  }
  return files;
}

export function staleFiles(courses = COURSES) {
  return derivedFiles(courses)
    .filter(
      ([file, contents]) =>
        !existsSync(file) || readFileSync(file, "utf8") !== contents,
    )
    .map(([file]) => file);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    const stale = staleFiles();
    for (const file of stale) console.error(`stale: ${file}`);
    process.exitCode = stale.length ? 1 : 0;
  } else {
    for (const [file, contents] of derivedFiles()) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== contents) {
        writeFileSync(file, contents);
        console.log(`updated ${file}`);
      }
    }
  }
}
